package art.arcane.iris.modded.mixin;

import art.arcane.iris.modded.toolworld.ToolWorldHooks;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.entity.BrewingStandBlockEntity;
import net.minecraft.world.level.block.state.BlockState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** A brewing stand of a tool world works only while the tool lets machines work there. */
@Mixin(BrewingStandBlockEntity.class)
public abstract class BrewingStandToolMixin {
    @Inject(method = "serverTick", at = @At("HEAD"), cancellable = true)
    private static void iris$askAboutBrewingStand(Level level, BlockPos position, BlockState state,
                                                  BrewingStandBlockEntity stand, CallbackInfo info) {
        if (!ToolWorldHooks.machineAllowed(level, position)) {
            info.cancel();
        }
    }
}
