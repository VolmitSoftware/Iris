package art.arcane.iris.modded.mixin;

import art.arcane.iris.modded.toolworld.ToolWorldHooks;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.commands.Commands;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** A command a player types in a tool world, or anyone types while one is open, is put to the tool before it runs. */
@Mixin(Commands.class)
public abstract class CommandsToolMixin {
    @Inject(method = "performPrefixedCommand", at = @At("HEAD"), cancellable = true)
    private void iris$askAboutCommand(CommandSourceStack source, String command, CallbackInfo info) {
        if (!ToolWorldHooks.commandAllowed(source, command)) {
            info.cancel();
        }
    }
}
