package art.arcane.iris.modded.mixin;

import art.arcane.iris.modded.toolworld.ToolWorldGuard;
import net.minecraft.core.BlockPos;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.level.block.Portal;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** A tool world has no portals: nothing standing in one is taken anywhere. */
@Mixin(Entity.class)
public abstract class EntityToolMixin {
    @Inject(method = "setAsInsidePortal", at = @At("HEAD"), cancellable = true)
    private void iris$keepToolWorldFreeOfPortals(Portal portal, BlockPos position, CallbackInfo info) {
        if (ToolWorldGuard.isToolWorld(((Entity) (Object) this).level())) {
            info.cancel();
        }
    }
}
