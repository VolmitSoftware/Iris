package art.arcane.iris.modded.mixin;

import art.arcane.iris.modded.toolworld.ToolWorldGuard;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/** Every change to a block of a tool world passes the tool world guard, which is where a tool world stays frozen. */
@Mixin(Level.class)
public abstract class LevelToolMixin {
    @Inject(
            method = "setBlock(Lnet/minecraft/core/BlockPos;Lnet/minecraft/world/level/block/state/BlockState;II)Z",
            at = @At("HEAD"),
            cancellable = true)
    private void iris$guardToolWorldBlock(BlockPos position, BlockState state, int flags, int recursionLeft,
                                          CallbackInfoReturnable<Boolean> result) {
        if (!ToolWorldGuard.setBlockAllowed((Level) (Object) this, position, state)) {
            result.setReturnValue(false);
        }
    }
}
