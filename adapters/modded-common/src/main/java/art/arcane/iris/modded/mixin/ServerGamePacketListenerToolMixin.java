package art.arcane.iris.modded.mixin;

import art.arcane.iris.modded.toolworld.ToolWorldHooks;
import net.minecraft.network.protocol.game.ServerboundSwingPacket;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.server.network.ServerGamePacketListenerImpl;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** A swing of the arm is the left click at nothing the tool hears about, unless it is aimed at a block. */
@Mixin(ServerGamePacketListenerImpl.class)
public abstract class ServerGamePacketListenerToolMixin {
    @Shadow
    public ServerPlayer player;

    @Inject(method = "handleAnimate", at = @At("HEAD"))
    private void iris$tellAboutSwing(ServerboundSwingPacket packet, CallbackInfo info) {
        ToolWorldHooks.leftClickAir(player, packet.getHand());
    }
}
