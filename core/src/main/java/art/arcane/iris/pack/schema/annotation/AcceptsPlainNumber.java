package art.arcane.iris.pack.schema.annotation;

import java.lang.annotation.Retention;
import java.lang.annotation.Target;

import static java.lang.annotation.ElementType.TYPE;
import static java.lang.annotation.RetentionPolicy.RUNTIME;

/**
 * Marks an object type that a pack may also write as a single number. The schema of a field of this type accepts
 * either the number, within the field's {@link MinNumber} and {@link MaxNumber}, or the object.
 */
@Retention(RUNTIME)
@Target({TYPE})
public @interface AcceptsPlainNumber {
}
