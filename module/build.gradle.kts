    compileOnly("com.volmit:iris-api")
    compileOnly(volmLibCoordinate) {
        isTransitive = false
    }
    compileOnly("com.google.code.gson:gson:2.14.0")
    compileOnly("org.projectlombok:lombok:1.18.46")
