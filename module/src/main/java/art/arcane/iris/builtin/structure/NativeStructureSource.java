package art.arcane.iris.builtin.structure;

import com.volmit.config.Desc;
import com.volmit.config.MinNumber;
import com.volmit.config.Ref;
import com.volmit.config.Reference;
import com.volmit.config.Required;
import com.volmit.vanilla.JigsawOverrides;

import java.util.Optional;

/**
 * One platform structure a structure placement starts itself, written as
 * {@code {"structure": "minecraft:ancient_city", "weight": 2, "jigsaw": {...}}}. IrisApi types only.
 */
@Desc("A live vanilla, datapack, or modded structure generated by Minecraft at an Iris-controlled placement.")
public final class NativeStructureSource {
    @Required
    @Ref(Reference.STRUCTURE)
    @Desc("Registered structure key. The source retains its native generator, pieces, templates, processors, entities, markers, and data.")
    private String structure = "";

    @MinNumber(1)
    @Desc("Relative selection weight when a placement offers multiple native structure sources.")
    private int weight = 1;

    @Desc("Optional jigsaw-only assembly overrides. Null preserves the complete registered structure definition.")
    private JigsawOverrides jigsaw = null;

    public NativeStructureSource() {
    }

    /** The registry key of the platform structure, as the pack wrote it. */
    public String structure() {
        return structure;
    }

    public int weight() {
        return weight;
    }

    /** The overrides of the platform's jigsaw assembly; empty to keep its own. */
    public Optional<JigsawOverrides> jigsaw() {
        return Optional.ofNullable(jigsaw);
    }
}
